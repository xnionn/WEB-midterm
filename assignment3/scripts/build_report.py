def render_and_check() -> dict:
    import pymupdf
    from pypdf import PdfReader
    TMP.mkdir(parents=True, exist_ok=True)
    doc = pymupdf.open(OUT)
    thumbs = []
    for i, page in enumerate(doc):
        pix = page.get_pixmap(matrix=pymupdf.Matrix(1.45, 1.45), alpha=False)
        path = TMP / f"page-{i + 1:02}.png"
        pix.save(path)
        im = Image.open(path).convert("RGB")
        im.thumbnail((340, 460))
        tile = Image.new("RGB", (370, 490), "#deded8")
        tile.paste(im, ((370 - im.width) // 2, 10))
        thumbs.append(tile)
    cols = 3
    sheet = Image.new("RGB", (cols * 370, ((len(thumbs) + cols - 1) // cols) * 490), "white")
    for i, tile in enumerate(thumbs):
        sheet.paste(tile, ((i % cols) * 370, (i // cols) * 490))
    sheet.save(TMP / "contact-sheet.png")
    reader = PdfReader(OUT)
    text = "\n".join(page.extract_text() or "" for page in reader.pages)
    for expected in ("Alimzhan Almukhambetov", "IT-2510", "Task 1", "Task 2", "Task 3", REPO, SOURCE, SITE):
        assert expected.lower() in text.lower(), expected
    links = [str(annotation.get_object().get("/A", {}).get("/URI", ""))
             for page in reader.pages for annotation in page.get("/Annots", [])]
    for url in (REPO, SOURCE, SITE):
        assert url in links, url
    report = {"pages": len(reader.pages), "bytes": OUT.stat().st_size, "required_text_and_links": "passed", "rendered_pages": len(doc), "visual_review": "required"}
    (TMP / "report-qa.json").write_text(json.dumps(report, indent=2), encoding="utf-8")
    return report


def main() -> None:
    global SHOTS
    parser = argparse.ArgumentParser()
    parser.add_argument("--screenshots", type=Path, default=SHOTS)
    args = parser.parse_args()
    SHOTS = args.screenshots.resolve()
    fonts()
    evidence_path = ROOT / "evidence" / "deployed" / "verification.json"
    evidence = json.loads(evidence_path.read_text(encoding="utf-8"))
    if evidence.get("passed") is not True or any(not check.get("passed") for check in evidence["checks"]):
        raise ValueError("The report requires successful hosted verification evidence.")
    r = Report()
    cover(r)
    task_one(r)
    task_one_screens(r)
    task_two(r)
    task_two_screens(r)
    comparison(r)
    overviews(r)
    conclusion(r, evidence)
    r.save()
    print(json.dumps(render_and_check(), indent=2))


if __name__ == "__main__":
    main()
