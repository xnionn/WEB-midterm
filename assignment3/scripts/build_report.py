def fonts() -> None:
    """Convert licensed local WOFF2 fonts to embedded static PDF fonts."""
    cache = ROOT / "tmp" / "report-fonts"
    cache.mkdir(parents=True, exist_ok=True)
    for name, filename, weight in (
        ("Space", "space-grotesk-latin-variable.woff2", 600),
        ("DM", "dm-sans-latin-variable.woff2", 400),
        ("DM-Bold", "dm-sans-latin-variable.woff2", 700),
    ):
        dest = cache / (name + ".ttf")
        if not dest.exists():
            src = ROOT / "assets" / "fonts" / filename
            if not src.exists():
                raise FileNotFoundError(f"Missing local font: {src}")
            font = FontToolsFont(src)
            axes = {axis.axisTag: axis.defaultValue for axis in font["fvar"].axes}
            axes["wght"] = weight
            font = instantiateVariableFont(font, axes, inplace=True)
            font.flavor = None
            for record in font["name"].names:
                if record.nameID in (1, 4, 6):
                    record.string = ("Assignment3Report" + name).encode(record.getEncoding())
            font.save(dest)
        pdfmetrics.registerFont(TTFont(name, str(dest)))
    pdfmetrics.registerFontFamily("DM", normal="DM", bold="DM-Bold", italic="DM", boldItalic="DM-Bold")
    for name, font, size, leading, color in (
        ("body", "DM", 11, 16, INK),
        ("small", "DM", 9.4, 13.3, MUTED),
        ("table", "DM", 9.5, 13.2, INK),
        ("table-head", "DM-Bold", 9.5, 13.2, colors.white),
    ):
        STYLES[name] = ParagraphStyle(name, fontName=font, fontSize=size, leading=leading, textColor=color)


class Report:
    def __init__(self) -> None:
        self.c = canvas.Canvas(str(OUT), pagesize=A4, pageCompression=1)
        self.c.setTitle("Assignment 3 - Responsive Web Design - Alimzhan Almukhambetov")
        self.c.setAuthor("Alimzhan Almukhambetov")
        self.c.setSubject("WEB Technologies 1; IT-2510; mobile-first CSS and Bootstrap 5.3")
        self.page_number = 0
        self.width, self.height = A4

    def new(self, label: str, title: str, *, wide: bool = False) -> float:
        if self.page_number:
            self.c.showPage()
        self.page_number += 1
        self.width, self.height = landscape(A4) if wide else A4
        c = self.c
        c.setPageSize((self.width, self.height))
        c.setFillColor(PAPER)
        c.rect(0, 0, self.width, self.height, fill=1, stroke=0)
        c.setFillColor(ORANGE)
        c.setFont("DM-Bold", 9)
        c.drawString(42, self.height - 42, label.upper())
        c.setFillColor(INK)
        c.setFont("Space", 25)
        c.drawString(42, self.height - 77, title)
        c.setStrokeColor(LINE)
        c.line(42, 41, self.width - 42, 41)
        c.setFillColor(MUTED)
        c.setFont("DM", 8)
        c.drawString(42, 25, "OFFLINE / Assignment 3 / Alimzhan Almukhambetov / IT-2510")
        c.drawRightString(self.width - 42, 25, f"{self.page_number:02}")
        return self.height - 100

    def para(self, text: str, y: float, *, x: float = 42, width: float | None = None, style: str = "body") -> float:
        p = Paragraph(text, STYLES[style])
        _, height = p.wrap(width or self.width - x - 42, 1200)
        if y - height < 55:
            raise ValueError(f"Text overflow on page {self.page_number}: {text[:65]}")
        p.drawOn(self.c, x, y - height)
        return y - height - 11

    def heading(self, title: str, y: float, *, x: float = 42, size: float = 16) -> float:
        self.c.setFont("Space", size)
        self.c.setFillColor(INK)
        self.c.drawString(x, y - size, title)
        return y - size - 12

    def table(self, rows: list[list[str]], y: float, widths: list[float]) -> float:
        cells = [[Paragraph(escape(cell), STYLES["table-head" if i == 0 else "table"])
                  for cell in row] for i, row in enumerate(rows)]
        t = Table(cells, colWidths=widths)
        t.setStyle(TableStyle([
            ("BACKGROUND", (0, 0), (-1, 0), INK),
            ("ROWBACKGROUNDS", (0, 1), (-1, -1), [colors.white, colors.HexColor("#eeeee6")]),
            ("LINEBELOW", (0, 0), (-1, -1), .5, LINE),
            ("VALIGN", (0, 0), (-1, -1), "TOP"),
            ("LEFTPADDING", (0, 0), (-1, -1), 9),
            ("RIGHTPADDING", (0, 0), (-1, -1), 9),
            ("TOPPADDING", (0, 0), (-1, -1), 10),
            ("BOTTOMPADDING", (0, 0), (-1, -1), 10),
        ]))
        _, height = t.wrap(sum(widths), 1400)
        if y - height < 55:
            raise ValueError(f"Table overflow on page {self.page_number}")
        t.drawOn(self.c, 42, y - height)
        return y - height - 18

    def code(self, lines: str, y: float, *, width: float | None = None, size: float = 8.5) -> float:
        content = lines.strip("\n").splitlines()
        leading = size * 1.52
        h = 24 + leading * len(content)
        if y - h < 55:
            raise ValueError(f"Code overflow on page {self.page_number}")
        self.c.setFillColor(INK)
        self.c.roundRect(42, y - h, width or self.width - 84, h, 4, stroke=0, fill=1)
        self.c.setFillColor(colors.HexColor("#fffdf5"))
        self.c.setFont("Courier", size)
        for i, line in enumerate(content):
            self.c.drawString(54, y - 17 - i * leading, line)
        return y - h - 18

    def picture(self, name: str, x: float, y: float, w: float, h: float, *, crop: tuple[int, int, int, int] | None = None) -> tuple[float, float]:
        path = SHOTS / name
        im = Image.open(path)
        if crop:
            im = im.crop(crop)
        scale = min(w / im.width, h / im.height)
        dw, dh = im.width * scale, im.height * scale
        self.c.setFillColor(colors.white)
        self.c.setStrokeColor(LINE)
        self.c.rect(x + (w - dw) / 2, y + h - dh, dw, dh, fill=1, stroke=1)
        self.c.drawImage(ImageReader(im), x + (w - dw) / 2, y + h - dh, dw, dh, mask="auto")
        return dw, dh

    def save(self) -> None:
        self.c.save()


